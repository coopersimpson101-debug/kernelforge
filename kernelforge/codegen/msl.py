"""Metal Shading Language backend. Byte-typed buffers are ``device const uchar*`` (MSL has native
8/16-bit loads, so ``expand_words`` is not run for this target)."""
from __future__ import annotations

from ..analysis import multiple_of
from ..ir import (Bin, Broadcast, ByteLoad, Call, Cast, Const, Decl, Expr, For, HalfLoad, Kernel, Lane,
                  Load, Select, Var, VecLoad, WordLoad, elem, lanes, show_stmt)
from .base import TextGen, ident
from .wgsl import _uses

_T = {"f32": "float", "i32": "int", "u32": "uint", "bool": "bool"}


def mtype(dt: str) -> str:
    n = lanes(dt)
    s = _T[elem(dt)]
    return s if n == 1 else f"{s}{n}"


def flit(v: float) -> str:
    r = repr(float(v))
    if "e" not in r and "." not in r:
        r += ".0"
    return r + "f"


_FN = {"exp": "exp", "sqrt": "sqrt", "rsqrt": "rsqrt", "tanh": "tanh", "abs": "fabs", "dot": "dot",
       "subgroup_add": "simd_sum", "subgroup_max": "simd_max"}


class MSLGen(TextGen):
    def e(self, x: Expr) -> str:
        if isinstance(x, Const):
            if x.dtype == "f32": return flit(x.value)
            if x.dtype == "u32": return f"{int(x.value)}u"
            if x.dtype == "bool": return "true" if x.value else "false"
            return str(int(x.value))
        if isinstance(x, Var):
            return x.name
        if isinstance(x, Bin):
            if x.op in ("min", "max"):
                return f"{x.op}({self.e(x.a)}, {self.e(x.b)})"
            return f"({self.e(x.a)} {x.op} {self.e(x.b)})"
        if isinstance(x, Select):
            return f"({self.e(x.cond)} ? {self.e(x.t)} : {self.e(x.f)})"
        if isinstance(x, Cast):
            return f"{mtype(x.dtype)}({self.e(x.e)})"
        if isinstance(x, Call):
            a = [self.e(y) for y in x.args]
            if x.fn == "hsum":
                n = lanes(x.args[0].dtype)
                return f"dot({a[0]}, float{n}(1.0f))"
            if x.fn == "sext8":
                return f"int(char({a[0]}))"
            if x.fn == "tanh":  # see codegen/wgsl.py: tanh_clamp (Metal fast-math tanh -> NaN for |x| > ~44)
                t = mtype(x.dtype)
                lo, hi = ("-10.0f", "10.0f") if lanes(x.dtype) == 1 else (f"{t}(-10.0f)", f"{t}(10.0f)")
                return f"tanh(clamp({a[0]}, {lo}, {hi}))"
            return f"{_FN[x.fn]}({', '.join(a)})"
        name = ident(x.buf.name) if hasattr(x, "buf") else ""
        if isinstance(x, Load):
            return f"{name}[{self.e(x.idx)}]"
        if isinstance(x, VecLoad):
            i = self.e(x.idx)
            if x.buf.scope == "global" and x.n == 4 and multiple_of(x.idx, self.defs) % 4 == 0:
                return f"((device const float4*){name})[({i}) / 4]"
            return f"float{x.n}({', '.join(f'{name}[{i} + {j}]' for j in range(x.n))})"
        if isinstance(x, ByteLoad):
            return f"uint({name}[{self.e(x.off)}])"
        if isinstance(x, HalfLoad):
            return f"float(*(device const half*)({name} + {self.e(x.off)}))"
        if isinstance(x, WordLoad):
            o = self.e(x.off)
            return (f"(uint({name}[{o}]) | (uint({name}[{o} + 1]) << 8) | (uint({name}[{o} + 2]) << 16)"
                    f" | (uint({name}[{o} + 3]) << 24))")
        if isinstance(x, Lane):
            return f"{self.e(x.e)}.{'xyzw'[x.i]}"
        if isinstance(x, Broadcast):
            return f"{mtype(x.dtype)}({self.e(x.e)})"
        raise NotImplementedError(f"msl: {x!r}")

    def for_head(self, s: For) -> str:
        v = s.var.name
        return f"for (int {v} = 0; {v} < {s.extent}; ++{v}) {{"

    def decl(self, s: Decl) -> str:
        kw = "" if s.mutable else "const "
        return f"{kw}{mtype(s.var.dtype)} {s.var.name} = {self.e(s.init)};"

    def barrier(self) -> str:
        return "threadgroup_barrier(mem_flags::mem_threadgroup);"

    def vec_tmp(self, name, val):
        return f"const {mtype(val.dtype)} {name} = {self.e(val)};"


def emit_msl(k: Kernel) -> str:
    g = MSLGen(k)
    g.v4 = set()  # MSL casts per access instead of re-typing the buffer
    out = [f"// generated by kernelforge: {k.name} (template {k.meta.get('template', '?')}, knobs {k.meta.get('knobs', {})})",
           "#include <metal_stdlib>", "using namespace metal;", ""]
    args = []
    for i, p in enumerate(k.params):
        b = k.buffers[k.alias.get(p.name, p.name)]
        el = {"f32": "float", "u32": "uint", "i32": "int", "bytes": "uchar"}[b.dtype]
        q = "device const" if b.readonly else "device"
        args.append(f"{q} {el}* {ident(b.name)} [[buffer({i})]]")
    args.append("uint3 lid [[thread_position_in_threadgroup]]")
    args.append("uint3 wid [[threadgroup_position_in_grid]]")
    out.append(f"kernel void {k.name}(" + ",\n    ".join(args) + ") {")
    body_text = show_stmt(k.body)
    for v, c in (("tx", "lid.x"), ("ty", "lid.y"), ("tz", "lid.z"), ("bx", "wid.x"), ("by", "wid.y"), ("bz", "wid.z")):
        if _uses(body_text, v):
            g.line(f"const int {v} = int({c});")
    for b in k.allocs:
        q = "threadgroup " if b.scope == "shared" else ""
        g.line(f"{q}{_T[b.dtype]} {ident(b.name)}[{b.size}];")
    g.stmt(k.body)
    out.extend(g.lines)
    out.append("}")
    return "\n".join(out) + "\n"
