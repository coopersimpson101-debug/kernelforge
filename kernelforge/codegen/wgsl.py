"""WGSL backend (WebGPU). Byte-typed buffers (f16 / Q8_0 / Q4_0) are bound as array<u32>; the
``expand_words`` pass has already rewritten narrow loads into word loads + shifts."""
from __future__ import annotations

from ..ir import (Bin, Broadcast, ByteLoad, Call, Cast, Const, Decl, Expr, For, HalfLoad, Kernel, Lane,
                  Load, Select, Var, VecLoad, WordLoad, elem, lanes, show_stmt)
from .base import TextGen, ident

_T = {"f32": "f32", "i32": "i32", "u32": "u32", "bool": "bool"}


def wtype(dt: str) -> str:
    n = lanes(dt)
    s = _T[elem(dt)]
    return s if n == 1 else f"vec{n}<{s}>"


def flit(v: float) -> str:
    r = repr(float(v))
    if "e" in r or "." in r:
        return r
    return r + ".0"


TANH_LIMIT = "10.0"


def tanh_clamp(arg: str, ty: str) -> str:
    """GPU tanh is commonly lowered as (e^2x - 1) / (e^2x + 1), which is inf/inf = NaN once e^2x
    overflows (|x| > ~44; Metal's default fast-math tanh does this). tanh(+-10) already rounds to
    +-1.0f in f32 (|1 - tanh(10)| = 4e-9 < half an ulp), so clamping the argument is exact."""
    lo, hi = (f"-{TANH_LIMIT}", TANH_LIMIT) if "<" not in ty else (f"{ty}(-{TANH_LIMIT})", f"{ty}({TANH_LIMIT})")
    return f"clamp({arg}, {lo}, {hi})"


_FN = {"exp": "exp", "sqrt": "sqrt", "rsqrt": "inverseSqrt", "tanh": "tanh", "abs": "abs", "dot": "dot",
       "subgroup_add": "subgroupAdd", "subgroup_max": "subgroupMax"}


class WGSLGen(TextGen):
    def e(self, x: Expr) -> str:
        if isinstance(x, Const):
            if x.dtype == "f32": return flit(x.value)
            if x.dtype == "u32": return f"{int(x.value)}u"
            if x.dtype == "bool": return "true" if x.value else "false"
            return str(int(x.value))
        if isinstance(x, Var):
            return x.name
        if isinstance(x, Bin):
            if x.op in (">>", "<<"):
                b = self.e(x.b) if x.b.dtype == "u32" else f"u32({self.e(x.b)})"
                return f"({self.e(x.a)} {x.op} {b})"
            return self.binop(x)
        if isinstance(x, Select):
            return f"select({self.e(x.f)}, {self.e(x.t)}, {self.e(x.cond)})"
        if isinstance(x, Cast):
            return f"{wtype(x.dtype)}({self.e(x.e)})"
        if isinstance(x, Call):
            a = [self.e(y) for y in x.args]
            if x.fn == "hsum":
                n = lanes(x.args[0].dtype)
                return f"dot({a[0]}, vec{n}<f32>(1.0))"
            if x.fn == "sext8":
                return f"(bitcast<i32>({a[0]} << 24u) >> 24u)"
            if x.fn == "tanh":
                return f"tanh({tanh_clamp(a[0], wtype(x.dtype))})"
            if x.fn == "unpack_lo_half":
                return f"unpack2x16float({a[0]}).x"
            return f"{_FN[x.fn]}({', '.join(a)})"
        if isinstance(x, Load):
            return f"{ident(x.buf.name)}[{self.e(x.idx)}]"
        if isinstance(x, VecLoad):
            name = ident(x.buf.name)
            if x.buf in self.v4:
                return f"{name}[({self.e(x.idx)}) / 4]"
            i = self.e(x.idx)
            return f"vec{x.n}<f32>({', '.join(f'{name}[{i} + {j}]' for j in range(x.n))})"
        if isinstance(x, Lane):
            return f"{self.e(x.e)}.{'xyzw'[x.i]}"
        if isinstance(x, Broadcast):
            return f"{wtype(x.dtype)}({self.e(x.e)})"
        raise NotImplementedError(f"wgsl: {x!r}")

    def for_head(self, s: For) -> str:
        v = s.var.name
        return f"for (var {v}: i32 = 0; {v} < {s.extent}; {v}++) {{"

    def decl(self, s: Decl) -> str:
        kw = "var" if s.mutable else "let"
        return f"{kw} {s.var.name}: {wtype(s.var.dtype)} = {self.e(s.init)};"

    def barrier(self) -> str:
        return "workgroupBarrier();"

    def vec_tmp(self, name, val):
        return f"let {name} = {self.e(val)};"


def emit_wgsl(k: Kernel) -> str:
    g = WGSLGen(k)
    out = [f"// generated by kernelforge: {k.name} (template {k.meta.get('template', '?')}, knobs {k.meta.get('knobs', {})})"]
    if "subgroups" in k.features:
        out.append("enable subgroups;")
    for i, p in enumerate(k.params):
        b = k.buffers[k.alias.get(p.name, p.name)]
        el = {"f32": "f32", "u32": "u32", "i32": "i32", "bytes": "u32"}[b.dtype]
        if b in g.v4:
            el = "vec4<f32>"
        acc = "read" if b.readonly else "read_write"
        out.append(f"@group(0) @binding({i}) var<storage, {acc}> {ident(b.name)}: array<{el}>;")
    for b in k.allocs:
        if b.scope == "shared":
            out.append(f"var<workgroup> {ident(b.name)}: array<{_T[b.dtype]}, {b.size}>;")
    wx, wy, wz = k.workgroup
    out.append("")
    out.append(f"@compute @workgroup_size({wx}, {wy}, {wz})")
    out.append(f"fn {k.name}(@builtin(local_invocation_id) lid: vec3<u32>, "
               f"@builtin(workgroup_id) wid: vec3<u32>) {{")
    body_text = show_stmt(k.body)
    for v, c in (("tx", "lid.x"), ("ty", "lid.y"), ("tz", "lid.z"), ("bx", "wid.x"), ("by", "wid.y"), ("bz", "wid.z")):
        if _uses(body_text, v):
            g.line(f"let {v} = i32({c});")
    for b in k.allocs:
        if b.scope == "local":
            g.line(f"var {ident(b.name)}: array<{_T[b.dtype]}, {b.size}>;")
    g.stmt(k.body)
    out.extend(g.lines)
    out.append("}")
    return "\n".join(out) + "\n"


def _uses(text: str, v: str) -> bool:
    import re
    return re.search(rf"\b{v}\b", text) is not None
